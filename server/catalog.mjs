export const serviceByKey = (key) => SERVICES.find((s) => s.key === key) || null

/** Price breakdown for `months` of a service, or null if that length is not offered. */
export function quote(service, months) {
  const d = DURATIONS.find((x) => x.months === months)
  if (!d || months < (service.minMonths || 1)) return null
  const gross = service.monthlyPrice * months
  const discount = Math.round((gross * d.discount) / 100 / 1000) * 1000
  return { months, discountPercent: d.discount, gross, discount, net: gross - discount }
}
